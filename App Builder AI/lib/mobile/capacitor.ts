import { SERVICE_WORKER_PATH, toBytes, type OutputFiles } from './pwa';

const APP_ID = /^[a-z][a-z0-9]*(\.[a-z][a-z0-9]*)+$/;

/** Reverse-DNS id that is valid for both Google Play (applicationId) and Apple (bundle identifier). */
export function validateAppId(appId: string): string | null {
  if (appId.length > 155) return 'App id is too long.';
  if (!APP_ID.test(appId)) {
    return 'Use a reverse-DNS id such as com.example.myapp: lowercase letters and digits, at least two dot-separated parts, each starting with a letter.';
  }
  return null;
}

export function suggestAppId(projectSlug: string) {
  const part = projectSlug.toLowerCase().replace(/[^a-z0-9]/g, '').replace(/^[0-9]+/, '') || 'app';
  return `com.appweaver.${part}`;
}

export type CapacitorOptions = {
  appId: string;
  appName: string;
  versionName: string;
  buildNumber: number;
  /** Optional live origin for hybrid mode; leave unset to bundle the web assets inside the app. */
  serverUrl?: string | null;
};

const CAPACITOR_VERSION = '^7.0.0';

export function generateCapacitorConfig(options: CapacitorOptions) {
  const serverBlock = options.serverUrl
    ? `  server: {\n    url: ${JSON.stringify(options.serverUrl)},\n    cleartext: false,\n  },\n`
    : '';
  return `import type { CapacitorConfig } from '@capacitor/cli';

const config: CapacitorConfig = {
  appId: ${JSON.stringify(options.appId)},
  appName: ${JSON.stringify(options.appName)},
  webDir: 'www',
${serverBlock}  android: { allowMixedContent: false },
  ios: { contentInset: 'automatic' },
};

export default config;
`;
}

export function generatePackageJson(options: CapacitorOptions) {
  const name = options.appName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'mobile-app';
  return (
    JSON.stringify(
      {
        name: `${name}-mobile`,
        version: options.versionName,
        private: true,
        scripts: {
          'cap:sync': 'cap sync',
          'cap:add:android': 'cap add android',
          'cap:add:ios': 'cap add ios',
          'cap:open:android': 'cap open android',
          'cap:open:ios': 'cap open ios',
        },
        dependencies: {
          '@capacitor/core': CAPACITOR_VERSION,
          '@capacitor/android': CAPACITOR_VERSION,
          '@capacitor/ios': CAPACITOR_VERSION,
        },
        devDependencies: { '@capacitor/cli': CAPACITOR_VERSION, typescript: '^5.0.0' },
      },
      null,
      2,
    ) + '\n'
  );
}

export function generateMobileReadme(options: CapacitorOptions) {
  return `# ${options.appName} - mobile wrapper (Capacitor)

Generated by AppWeaver AI. This is an exportable project, NOT a compiled app: you build the
Android and iOS binaries yourself (or on your own CI) with the steps below.

- App id: \`${options.appId}\`
- Version: ${options.versionName} (build ${options.buildNumber})
- Web assets: \`www/\` (your project's built output, with PWA assets)

## Prerequisites
- Node.js 20+
- Android: Android Studio (with an SDK and JDK 17+)
- iOS: a Mac with Xcode, CocoaPods, and an Apple Developer Program membership (required to run on devices and to publish)

## Steps
\`\`\`bash
npm install
npx cap add android      # once
npx cap add ios          # once, on macOS
npx cap sync             # after every change to www/
npx cap open android     # build / run from Android Studio
npx cap open ios         # build / run from Xcode
\`\`\`

## Version numbers
Set the version in each native project before release:
- Android: \`versionName\` ${options.versionName} and \`versionCode\` ${options.buildNumber} in \`android/app/build.gradle\`.
- iOS: Marketing Version ${options.versionName} and Build ${options.buildNumber} in Xcode.
Each store upload needs a higher build number than the previous one.

## Signing and publishing
- Android: create an upload keystore (\`keytool -genkeypair ...\`), build a signed Android App Bundle (.aab) in Android Studio
  (Build > Generate Signed Bundle), and upload it to Google Play Console. Keep the keystore and passwords safe; losing them blocks updates.
- iOS: create the app in App Store Connect, set the Team and signing in Xcode, Product > Archive, then upload via the Organizer.
- Complete the store listing, privacy policy, data-safety / privacy nutrition labels and age rating in each console.

## Icons and splash screens
Place a 1024x1024 \`resources/icon.png\` and 2732x2732 \`resources/splash.png\`, then run
\`npx @capacitor/assets generate\`.

## Notes
- The service worker (\`${SERVICE_WORKER_PATH}\`) works inside the Android WebView; iOS WKWebView does not run service workers for the app origin, so the bundled assets provide the offline behaviour there.
- Store review requires more than a thin web wrapper: add genuine app functionality (e.g. native plugins) and comply with each store's guidelines.
`;
}

const GITIGNORE = `node_modules/\nandroid/app/build/\nandroid/.gradle/\nios/App/Pods/\nios/App/build/\n*.keystore\n*.jks\n*.p8\n*.p12\n*.mobileprovision\n`;

export function buildCapacitorProjectFiles(web: OutputFiles, options: CapacitorOptions): OutputFiles {
  const out: OutputFiles = {};
  for (const [path, bytes] of Object.entries(web)) out[`www/${path}`] = bytes;
  out['capacitor.config.ts'] = toBytes(generateCapacitorConfig(options));
  out['package.json'] = toBytes(generatePackageJson(options));
  out['README-MOBILE.md'] = toBytes(generateMobileReadme(options));
  out['.gitignore'] = toBytes(GITIGNORE);
  out['resources/README.md'] = toBytes('Add icon.png (1024x1024) and splash.png (2732x2732) here, then run `npx @capacitor/assets generate`.\n');
  return out;
}
