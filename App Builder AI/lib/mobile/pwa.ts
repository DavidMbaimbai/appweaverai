export type OutputFiles = Record<string, Uint8Array>;

const encoder = new TextEncoder();
const decoder = new TextDecoder();

export const toBytes = (text: string) => encoder.encode(text);
export const toText = (bytes: Uint8Array) => decoder.decode(bytes);

export type PwaOptions = {
  name: string;
  shortName?: string;
  description?: string;
  themeColor?: string;
  backgroundColor?: string;
  startUrl?: string;
  scope?: string;
  display?: 'standalone' | 'fullscreen' | 'minimal-ui' | 'browser';
  lang?: string;
};

export const MANIFEST_PATH = 'manifest.webmanifest';
export const SERVICE_WORKER_PATH = 'sw.js';
export const OFFLINE_PAGE_PATH = 'offline.html';
export const ICON_SVG_PATH = 'icons/icon.svg';

/** Icons a store-quality PWA ships. PNGs cannot be rendered here, so only the SVG source is generated. */
export const ICON_SPEC = [
  { path: 'icons/icon-192.png', sizes: '192x192', purpose: 'any', required: true, note: 'Chrome install prompt minimum' },
  { path: 'icons/icon-512.png', sizes: '512x512', purpose: 'any', required: true, note: 'Splash screen and install dialog' },
  { path: 'icons/icon-maskable-512.png', sizes: '512x512', purpose: 'maskable', required: false, note: 'Keep artwork inside the central 80% safe zone' },
  { path: 'icons/apple-touch-icon.png', sizes: '180x180', purpose: 'any', required: false, note: 'iOS home-screen icon (link rel="apple-touch-icon")' },
] as const;

const HEX_COLOR = /^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/;

export function safeColor(value: string | undefined, fallback: string) {
  return value && HEX_COLOR.test(value) ? value : fallback;
}

function clip(value: string, max: number) {
  return value.trim().slice(0, max);
}

export function generateManifest(options: PwaOptions) {
  const name = clip(options.name, 45) || 'App';
  const manifest = {
    name,
    short_name: clip(options.shortName || name, 12),
    description: clip(options.description ?? '', 300) || undefined,
    id: options.startUrl ?? './',
    start_url: options.startUrl ?? './',
    scope: options.scope ?? './',
    display: options.display ?? 'standalone',
    orientation: 'any',
    lang: options.lang ?? 'en',
    theme_color: safeColor(options.themeColor, '#111827'),
    background_color: safeColor(options.backgroundColor, '#ffffff'),
    icons: [
      ...ICON_SPEC.filter((icon) => icon.purpose === 'any' && icon.sizes !== '180x180').map((icon) => ({
        src: icon.path,
        sizes: icon.sizes,
        type: 'image/png',
        purpose: icon.purpose,
      })),
      { src: ICON_SPEC[2].path, sizes: ICON_SPEC[2].sizes, type: 'image/png', purpose: 'maskable' },
    ],
  };
  return JSON.stringify(manifest, null, 2) + '\n';
}

export function generateServiceWorker(options: { cacheVersion: string; precache: string[] }) {
  const version = options.cacheVersion.replace(/[^A-Za-z0-9._-]/g, '');
  const urls = [...new Set([OFFLINE_PAGE_PATH, ...options.precache])];
  return `/* Generated by AppWeaver AI. Network-first for pages with an offline fallback; cache-first for static assets. */
const CACHE = 'app-shell-${version}';
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('${OFFLINE_PAGE_PATH}')));
    return;
  }

  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;
}

function escapeHtml(value: string) {
  return value.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] as string);
}

export function generateOfflinePage(name: string, themeColor = '#111827') {
  const title = escapeHtml(name);
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${title} - offline</title>
  <style>
    body { margin: 0; min-height: 100vh; display: grid; place-items: center; font-family: system-ui, sans-serif; text-align: center; padding: 24px; }
    h1 { color: ${safeColor(themeColor, '#111827')}; }
  </style>
</head>
<body>
  <main>
    <h1>You are offline</h1>
    <p>${title} needs a connection for this page. Check your network and try again.</p>
    <button onclick="location.reload()">Retry</button>
  </main>
</body>
</html>
`;
}

export function generateIconSvg(name: string, themeColor = '#111827') {
  const letter = escapeHtml((name.trim()[0] ?? 'A').toUpperCase());
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><rect width="512" height="512" fill="${safeColor(themeColor, '#111827')}"/><text x="256" y="340" font-family="system-ui, sans-serif" font-size="280" font-weight="700" text-anchor="middle" fill="#ffffff">${letter}</text></svg>
`;
}

const REGISTER_SNIPPET = `<script>if ('serviceWorker' in navigator) { window.addEventListener('load', function () { navigator.serviceWorker.register('${SERVICE_WORKER_PATH}'); }); }</script>`;

/** Idempotently adds viewport, theme colour, manifest link, apple-touch-icon and service-worker registration. */
export function injectPwaIntoHtml(html: string, themeColor: string) {
  const additions: string[] = [];
  if (!/<meta[^>]+name=["']viewport["']/i.test(html)) {
    additions.push('<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />');
  }
  if (!/<meta[^>]+name=["']theme-color["']/i.test(html)) {
    additions.push(`<meta name="theme-color" content="${safeColor(themeColor, '#111827')}" />`);
  }
  if (!/<link[^>]+rel=["']manifest["']/i.test(html)) {
    additions.push(`<link rel="manifest" href="${MANIFEST_PATH}" />`);
  }
  if (!/<link[^>]+rel=["']apple-touch-icon["']/i.test(html)) {
    additions.push('<link rel="apple-touch-icon" href="icons/apple-touch-icon.png" />');
  }
  let out = html;
  if (additions.length > 0) {
    const block = additions.map((line) => `  ${line}`).join('\n');
    out = /<head[^>]*>/i.test(out) ? out.replace(/<head([^>]*)>/i, `<head$1>\n${block}`) : `${block}\n${out}`;
  }
  if (!/serviceWorker\.register/.test(out)) {
    out = /<\/body>/i.test(out) ? out.replace(/<\/body>/i, `  ${REGISTER_SNIPPET}\n</body>`) : `${out}\n${REGISTER_SNIPPET}\n`;
  }
  return out;
}

export type PwaGenerationResult = { files: OutputFiles; added: string[]; kept: string[] };

/** Adds PWA assets to the built output. Files the project already has are never overwritten (index.html is only patched). */
export function applyPwa(input: OutputFiles, options: PwaOptions, cacheVersion = 'v1'): PwaGenerationResult {
  const files: OutputFiles = { ...input };
  const added: string[] = [];
  const kept: string[] = [];
  const theme = safeColor(options.themeColor, '#111827');

  const addIfMissing = (path: string, content: string) => {
    if (path in files) kept.push(path);
    else {
      files[path] = toBytes(content);
      added.push(path);
    }
  };

  const html = files['index.html'];
  if (html) {
    const patched = injectPwaIntoHtml(toText(html), theme);
    if (patched !== toText(html)) {
      files['index.html'] = toBytes(patched);
      added.push('index.html (patched)');
    }
  }

  addIfMissing(MANIFEST_PATH, generateManifest(options));
  addIfMissing(OFFLINE_PAGE_PATH, generateOfflinePage(options.name, theme));
  addIfMissing(ICON_SVG_PATH, generateIconSvg(options.name, theme));

  const precache = Object.keys(files).filter(
    (path) => /\.(html|css|js|mjs|json|webmanifest|svg|png|jpe?g|webp|woff2?)$/i.test(path) && path !== SERVICE_WORKER_PATH,
  );
  addIfMissing(
    SERVICE_WORKER_PATH,
    generateServiceWorker({ cacheVersion, precache: precache.slice(0, 60) }),
  );

  return { files, added, kept };
}

